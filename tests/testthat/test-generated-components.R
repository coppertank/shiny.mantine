  expect_equal(TooltipGroup()$name, "TooltipGroup")
  expect_equal(Typography()$name, "Typography")
  expect_equal(VisuallyHidden()$name, "VisuallyHidden")
})

test_that("generated components forward props through to the JSON tree", {
  el <- Fieldset(legend = "Personal info")
  expect_equal(el$props$legend, list(type = "raw", value = "Personal info"))
})
